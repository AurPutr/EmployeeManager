import os          # os.getenv - nuskaityti DATABASE_URL iš aplinkos kintamųjų
import sys         # sys.stdout - sutvarkyti išvedimą Windows konsolėje
import tomllib     # tomllib - perskaityti .streamlit/secrets.toml failą
from pathlib import Path  # Path - patogus darbas su failų keliais

import pandas as pd   # pandas - Excel/CSV nuskaitymas ir duomenų pertvarkymas
import psycopg2       # psycopg2 - PostgreSQL duomenų bazės driver'is


if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(errors="replace") #LT raidziu gavimui


# ============================================
# PRISIJUNGIMO DUOMENYS
# ============================================

BASE_DIR = Path(__file__).resolve().parent


def get_database_url():
    """Grąžina PostgreSQL prisijungimo eilutę (DATABASE_URL)."""

    url = os.getenv("DATABASE_URL")
    if url:
        return url

    secrets_path = BASE_DIR / ".streamlit" / "secrets.toml"
    if secrets_path.exists():
        with secrets_path.open("rb") as file:
            return tomllib.load(file)["DATABASE_URL"]

    raise SystemExit(
        f"Nerastas DATABASE_URL. Sukurkite {secrets_path} su eilute:\n"
        'DATABASE_URL = "postgresql://user:password@localhost:5432/employeeManager"\n'
        'macOS atveju: DATABASE_URL = "postgresql://localhost:5432/employeeManager"'
    )


# ============================================
# STULPELIŲ ATITIKIMAS
# ============================================

COLUMNS = [
    "id",
    "name",
    "surname",
    "email",
    "team_id",
    "position_id",
    "ticketron_id",
    "do_evaluations",
    "start_date",
    "end_date",
    "status",
    "onboarded",
]


# ============================================
# FAILO PAIEŠKA IR NUSKAITYMAS
# ============================================

def find_source_file():
    """Suranda duomenų failą: pirmiausia Excel, po to CSV."""

    for file_name in ("employees.xlsx", "employees.csv"): #excelio filo pavadinimai keiciami cia
        path = BASE_DIR / file_name
        if path.exists():
            return path

    raise SystemExit(f"Nerastas employees.xlsx arba employees.csv kataloge {BASE_DIR}")


def read_employees(path):
    """Nuskaito failą, pervadina stulpelius ir grąžina tik reikalingus stulpelius."""

    if path.suffix.lower() == ".xlsx":
        try:
            df = pd.read_excel(path)
        except ImportError:
            raise SystemExit(
                "Excel failui nuskaityti reikia openpyxl bibliotekos:\n"
                "pip3 install openpyxl"
            )
    else:
        df = pd.read_csv(path, encoding="utf-8")

    df.columns = [str(column).strip() for column in df.columns]

    return df[COLUMNS]

# ============================================
# SQL UŽKLAUSOS
# ============================================

CREATE_TABLE_SQL = """
    CREATE TABLE IF NOT EXISTS employee (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) NOT NULL,
        surname VARCHAR(100) NOT NULL,
        email VARCHAR(255) NOT NULL UNIQUE,
        team_id VARCHAR(100) NOT NULL,
        position_id VARCHAR(100) NOT NULL,
        ticketron_id INTEGER,
        do_evaluations VARCHAR(100) NOT NULL,
        start_date DATE,
        end_date DATE,
        status VARCHAR(50),
        onboarded VARCHAR(50) NOT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMP NOT NULL DEFAULT NOW()
    )
"""
#imit info is main.py ir ikelti lenteliu info cia

INSERT_SQL = """
    INSERT INTO employee (
        id, name, surname, email, team_id, position_id, ticketron_id,
        do_evaluations, start_date, end_date, status, onboarded
    )
    VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
    ON CONFLICT (id) DO UPDATE SET
        name = EXCLUDED.name,
        surname = EXCLUDED.surname,
        email = EXCLUDED.email,
        team_id = EXCLUDED.team_id,
        position_id = EXCLUDED.position_id,
        ticketron_id = EXCLUDED.ticketron_id,
        do_evaluations = EXCLUDED.do_evaluations,
        start_date = EXCLUDED.start_date,
        end_date = EXCLUDED.end_date,
        status = EXCLUDED.status,
        onboarded = EXCLUDED.onboarded
"""
#nededam ID ir created_at ir updated_at on conflict dalyje

SYNC_SEQUENCE_SQL = """
    SELECT setval(
        pg_get_serial_sequence('employee', 'id'),
        COALESCE(MAX(id), 0) + 1,
        false
    )
    FROM employee
"""

def convert_dates(series):
    """Paverčia stulpelį į datų sąrašą; tuščios vietų -> None (SQL NULL)."""

    # errors="coerce": netinkamos/tuščios reikšmės net kelia klaidos, o tampa NaT

    parsed = pd.to_datetime(series, errors="coerce")

    # Kiekvieną reikšmę: jei NaT/NaN -> None, kitaip -> tikra data (date)

    return [None if pd.isna(value) else value.date() for value in parsed]

def build_rows(df):
    """DataFrame paverčia sąrašu eilučių, tinkamų siųsti į INSERT užklausą."""

    df = df.copy()  # dirbame su kopija, kad nepakeistume originalo

    # Tekstas -> datos
    df["start_date"] = convert_dates(df["start_date"])

    df["end_date"] = convert_dates(df["end_date"])


    # Tekstinius laukus apkerpame (pašaliname nereikalingus tarpus)
    for column in ("name", "surname", "email", "status"):
        df[column] = df[column].astype(str).str.strip()

    # Skaičiai turi būti int, kitaip psycopg2 siųstų netinkamą tipą
    df["id"] = df["id"]
    df["team_id"] = df["team_id"]

    # itertuples grąžina kiekvieną eilutę kaip sąrašą reikiama stulpelių tvarka
    return list(df[COLUMNS].itertuples(index=False, name=None))


def main():
    """Pagrindinė programa: nuskaitymas -> įrašymas -> patikrinimas."""

    # 1. Surandamas ir nuskaitomas failas
    source = find_source_file()
    print(f"Nuskaitomas failas: {source.name}")

    df = read_employees(source)
    rows = build_rows(df)
    print(f"Rasta eilučių: {len(rows)}")

    # 2. Prisijungiama prie duomenų bazės
    conn = psycopg2.connect(get_database_url())
    cursor = conn.cursor()

    try:
        # 3. Sukuriama lentelė, jei jos dar nėra
        cursor.execute(CREATE_TABLE_SQL)
        conn.commit()

        # 4. Visos eilutės įrašomos viena užklausa (executemany).
        #    ON CONFLICT (id) DO UPDATE - esamas id atnaujinamas, ne dubliuojamas,
        #    todėl skriptą galima paleisti daug kartų
        cursor.executemany(INSERT_SQL, rows)
        conn.commit()
        print(f"Įkelta į lentelę employee: {cursor.rowcount}")

        # 5. Sinchronizuojama id seka, kad app.py formos įrašai nesidubliuotų
        cursor.execute(SYNC_SEQUENCE_SQL)
        conn.commit()

        # 6. Patikrinimas - išvedame, kas dabar yra lentelėje
        cursor.execute("SELECT * FROM employee ORDER BY id")
        for row in cursor.fetchall():
            print(row)

        cursor.execute("SELECT COUNT(*) FROM employee")
        print(f"Iš viso lentelėje: {cursor.fetchone()[0]}")
    finally:
        # Ryšys uždaromas net jei įvyko klaida
        cursor.close()
        conn.close()


# Šis blokas paleidžiamas tik tada, kai failas vykdomas tiesiogiai
# (jei kas nors jį importuotų, main() automatiškai nepasileistų)
if __name__ == "__main__":
    main()
